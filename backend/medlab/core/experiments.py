"""Experiment service: run a lab, persist metadata in SQLite and arrays on disk."""

from __future__ import annotations

import uuid
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any

import numpy as np
from numpy.typing import NDArray
from pydantic import ValidationError
from sqlalchemy import select
from sqlalchemy.orm import Session

from medlab.core import storage
from medlab.core.models import ExperimentRow
from medlab.labs.ecg import pipeline as ecg_pipeline
from medlab.labs.ecg.filters import FilterConfigError
from medlab.labs.hmi import analysis as hmi_analysis
from medlab.labs.reaction import analysis as reaction_analysis
from medlab.schemas.common import DataSource, ModelInfo, Parameter, ValidationCheck
from medlab.schemas.ecg import EcgSimulationRequest
from medlab.schemas.experiment import (
    ExecutionStatus,
    ExperimentCreate,
    ExperimentDetail,
    ExperimentSummary,
    LabType,
    RerunResult,
)
from medlab.schemas.hmi import HmiDataset
from medlab.schemas.reaction import ReactionDataset


class LabNotAvailableError(Exception):
    pass


class InvalidConfigError(Exception):
    pass


class ExperimentNotFoundError(Exception):
    pass


@dataclass(frozen=True)
class LabRun:
    """Normalised output of one laboratory run, independent of the lab."""

    model: ModelInfo
    algorithm_versions: dict[str, str]
    parameters: list[Parameter]
    data_sources: list[DataSource]
    validation: list[ValidationCheck]
    seed: int | None
    response: dict[str, Any]
    summary: dict[str, Any]
    arrays: dict[str, NDArray[Any]]
    visualization: dict[str, Any]
    result_hash: str


def _run_ecg(config: dict[str, Any]) -> LabRun:
    try:
        req = EcgSimulationRequest.model_validate(config)
        result = ecg_pipeline.run_simulation(req)
    except (ValidationError, FilterConfigError) as exc:
        raise InvalidConfigError(str(exc)) from exc
    resp = result.response
    summary = {
        "r_peaks": None
        if resp.r_peaks is None
        else {
            "method": resp.r_peaks.method,
            "count": len(resp.r_peaks.indices),
            "estimated_hr_bpm": resp.r_peaks.estimated_hr_bpm,
            "hr_sd_bpm": resp.r_peaks.hr_sd_bpm,
        },
        "true_beat_count": len(resp.true_r_times_s),
        "stats": resp.stats.model_dump(),
        "samples": len(resp.time_s),
    }
    return LabRun(
        model=resp.model,
        algorithm_versions=resp.algorithm_versions,
        parameters=resp.parameters,
        data_sources=[
            DataSource(
                kind="synthetic",
                name="Synthetic Lead II ECG",
                description="Generated by the gaussian-wave-sum model; no patient data.",
            )
        ],
        validation=resp.validation,
        seed=req.seed,
        response=resp.model_dump(mode="json"),
        summary=summary,
        arrays={
            "time_s": result.arrays.time_s,
            "clean_mv": result.arrays.clean_mv,
            "noisy_mv": result.arrays.noisy_mv,
            "filtered_mv": result.arrays.filtered_mv,
            "true_r_times_s": result.arrays.true_r_times_s,
            "r_peak_indices": result.arrays.r_peak_indices,
        },
        visualization={"chart": "ecg-compare", "traces": ["noisy_mv", "filtered_mv", "clean_mv"]},
        result_hash=resp.result_hash,
    )


def _run_reaction(config: dict[str, Any]) -> LabRun:
    try:
        ds = ReactionDataset.model_validate(config)
    except ValidationError as exc:
        raise InvalidConfigError(str(exc)) from exc
    resp = reaction_analysis.analyse(ds)
    rts = np.array(
        [t.reaction_ms if t.reaction_ms is not None else np.nan for t in resp.trials],
        dtype=np.float64,
    )
    return LabRun(
        model=resp.model,
        algorithm_versions=resp.algorithm_versions,
        parameters=resp.parameters,
        data_sources=[resp.data_source],
        validation=resp.validation,
        seed=ds.design.seed,
        response=resp.model_dump(mode="json"),
        summary={
            "counts": resp.counts.model_dump(),
            "median_ms": resp.summary.median,
            "mean_ms": resp.summary.mean,
            "sd_ms": resp.summary.sd,
            "task": ds.design.task.value,
            "source": ds.source,
        },
        arrays={
            "reaction_ms": rts,
            "valid": np.array([t.valid for t in resp.trials]),
            "outlier": np.array([t.outlier for t in resp.trials]),
        },
        visualization={"chart": "rt-histogram-sequence"},
        result_hash=resp.result_hash,
    )


def _run_hmi(config: dict[str, Any]) -> LabRun:
    try:
        ds = HmiDataset.model_validate(config)
    except ValidationError as exc:
        raise InvalidConfigError(str(exc)) from exc
    resp = hmi_analysis.analyse(ds)
    return LabRun(
        model=resp.model,
        algorithm_versions=resp.algorithm_versions,
        parameters=resp.parameters,
        data_sources=[resp.data_source],
        validation=resp.validation,
        seed=ds.design.seed,
        response=resp.model_dump(mode="json"),
        summary={
            "variants": {
                k.value: {
                    "n_tasks": v.n_tasks,
                    "success_rate": v.success_rate,
                    "median_time_ms": v.time.median,
                    "errors_total": v.errors_total,
                    "tlx_overall": v.tlx_overall,
                }
                for k, v in resp.variants.items()
            },
            "time_mann_whitney_p": resp.comparison.time.mann_whitney_p,
            "errors_fisher_p": resp.comparison.errors.fisher_p,
        },
        arrays={
            "duration_ms": np.array([r.duration_ms for r in resp.results], dtype=np.float64),
            "variant_is_b": np.array([r.variant.value == "B" for r in resp.results]),
            "success": np.array([r.success for r in resp.results]),
        },
        visualization={"chart": "hmi-ab-compare"},
        result_hash=resp.result_hash,
    )


RUNNERS = {LabType.ECG: _run_ecg, LabType.REACTION_TIME: _run_reaction, LabType.HMI: _run_hmi}


def run_lab(lab_type: LabType, config: dict[str, Any]) -> LabRun:
    runner = RUNNERS.get(lab_type)
    if runner is None:
        raise LabNotAvailableError(f"lab '{lab_type}' has no runnable model yet")
    return runner(config)


def _to_summary(row: ExperimentRow) -> ExperimentSummary:
    return ExperimentSummary(
        id=row.id,
        name=row.name,
        lab_type=LabType(row.lab_type),
        description=row.description,
        model=ModelInfo(
            name=row.model_name, version=row.model_version, description=row.model_description
        ),
        seed=row.seed,
        status=ExecutionStatus(row.status),
        created_at=row.created_at,
        result_hash=row.result_hash,
    )


def _to_detail(row: ExperimentRow, include_results: bool = True) -> ExperimentDetail:
    summary = _to_summary(row)
    results: dict[str, Any] = dict(row.results_summary)
    if include_results:
        full = storage.read_response(row.id)
        if full is not None:
            results = {**results, "response": full}
    return ExperimentDetail(
        **summary.model_dump(),
        parameters=[Parameter.model_validate(p) for p in row.parameters],
        data_sources=[DataSource.model_validate(d) for d in row.data_sources],
        config=row.config,
        algorithm_versions=row.algorithm_versions,
        results=results,
        visualization=row.visualization,
        validation=[ValidationCheck.model_validate(v) for v in row.validation],
    )


def create_experiment(session: Session, payload: ExperimentCreate) -> ExperimentDetail:
    run = run_lab(payload.lab_type, payload.config)
    experiment_id = str(uuid.uuid4())
    directory = storage.write_results(experiment_id, run.response, run.arrays)
    row = ExperimentRow(
        id=experiment_id,
        name=payload.name,
        lab_type=payload.lab_type.value,
        description=payload.description,
        model_name=run.model.name,
        model_version=run.model.version,
        model_description=run.model.description,
        seed=run.seed,
        status=ExecutionStatus.COMPLETED.value,
        created_at=datetime.now(UTC),
        result_hash=run.result_hash,
        parameters=[p.model_dump(mode="json") for p in run.parameters],
        data_sources=[d.model_dump(mode="json") for d in run.data_sources],
        config=payload.config,
        algorithm_versions=run.algorithm_versions,
        results_summary=run.summary,
        visualization=run.visualization,
        validation=[v.model_dump(mode="json") for v in run.validation],
        storage_dir=str(directory.relative_to(directory.parents[1])),
    )
    session.add(row)
    session.commit()
    return _to_detail(row)


def list_experiments(session: Session, lab_type: LabType | None = None) -> list[ExperimentSummary]:
    stmt = select(ExperimentRow).order_by(ExperimentRow.created_at.desc())
    if lab_type is not None:
        stmt = stmt.where(ExperimentRow.lab_type == lab_type.value)
    return [_to_summary(row) for row in session.scalars(stmt)]


def _get_row(session: Session, experiment_id: str) -> ExperimentRow:
    row = session.get(ExperimentRow, experiment_id)
    if row is None:
        raise ExperimentNotFoundError(experiment_id)
    return row


def get_experiment(session: Session, experiment_id: str) -> ExperimentDetail:
    return _to_detail(_get_row(session, experiment_id))


def delete_experiment(session: Session, experiment_id: str) -> None:
    row = _get_row(session, experiment_id)
    session.delete(row)
    session.commit()
    storage.delete_results(experiment_id)


def rerun_experiment(session: Session, experiment_id: str) -> RerunResult:
    """Recompute from the stored config and report whether the result hash is unchanged."""
    row = _get_row(session, experiment_id)
    previous_hash = row.result_hash
    run = run_lab(LabType(row.lab_type), row.config)
    storage.write_results(row.id, run.response, run.arrays)
    row.result_hash = run.result_hash
    row.algorithm_versions = run.algorithm_versions
    row.results_summary = run.summary
    row.validation = [v.model_dump(mode="json") for v in run.validation]
    row.status = ExecutionStatus.COMPLETED.value
    session.commit()
    return RerunResult(
        experiment=_to_detail(row),
        reproducible=previous_hash == run.result_hash,
        previous_hash=previous_hash,
        new_hash=run.result_hash,
    )
